    def close_db_connections(self):
        """关闭所有数据库连接（用于备份恢复前）"""
        try:
            # 检查并关闭所有可能打开的数据库连接
            if hasattr(self, 'conn') and self.conn:
                try:
                    self.conn.close()
                except Exception as e:
                    print(f"关闭主连接时出错: {str(e)}")
                finally:
                    self.conn = None
            
            # 关闭可能在查询中打开的临时连接
            for attr in dir(self):
                if attr.startswith('_db_conn_'):
                    conn = getattr(self, attr)
                    if conn:
                        try:
                            conn.close()
                        except:
                            pass
                        finally:
                            setattr(self, attr, None)
            
            # 确保SQLite文件没有被锁定
            if os.path.exists('phone_numbers.db'):
                try:
                    # 尝试打开文件以确认是否可访问
                    with open('phone_numbers.db', 'rb'):
                        pass
                except IOError as e:
                    print(f"数据库文件仍被锁定: {str(e)}")
                    # 如果是Windows系统，尝试强制关闭
                    if sys.platform == 'win32':
                        try:
                            os.system('taskkill /f /im sqlite3.exe')
                        except:
                            pass
            
            # 额外等待确保连接完全关闭
            time.sleep(0.5)
            
        except Exception as e:
            print(f"关闭数据库连接时发生错误: {str(e)}")
            raise RuntimeError("无法安全关闭数据库连接") from e

    
